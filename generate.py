class GenerateError(Exception):
    pass


@dataclass
class Recovery:
    """What the generated tree takes from the stock recovery image."""

    partition_size: int
    header_version: int
    files: dict[str, bytes]
    props: dict[str, str]


@dataclass
class Section:
    """What a group of stock files adds to the generated tree."""

    texts: dict[str, str] = field(default_factory=dict)
    files: dict[str, bytes] = field(default_factory=dict)
    modules: list[str] = field(default_factory=list)
    blueprints: list[str] = field(default_factory=list)
    copies: list[str] = field(default_factory=list)


@dataclass
class Device:
    config: dict
    inputs: dict

    @property
    def vendor(self) -> str:
        return self.config["vendor"]

    @property
    def name(self) -> str:
        return self.config["device"]

    @property
    def out_path(self) -> str:
        return f"vendor/{self.vendor}/{self.name}"

    @property
    def mk_path(self) -> str:
        return f"{MDEVTOOL_PATH}/config/mk/{self.vendor}"

    @property
    def spec_file(self) -> Path:
        return MDEVTOOL / "vendor-specs" / self.vendor / f"{self.name}.json"

    @property
    def skel_dir(self) -> Path:
        return MDEVTOOL / "vendor-skels" / self.vendor / self.name


def load_device(name: str) -> Device:
    directory = MDEVTOOL / "config/device"
    try:
        config = json.loads((directory / f"{name}.json").read_text())
        inputs = json.loads((directory / f"{name}-inputs.json").read_text())
    except FileNotFoundError as error:
        raise GenerateError(
            f"Unknown device {name}: {error.filename} is missing"
        ) from None
    return Device(config, inputs)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as file:
        while chunk := file.read(1 << 20):
            digest.update(chunk)
    return digest.hexdigest()


def verify_input(device: Device, root: Path, name: str) -> Path:
    """Check a stock image and return its path under the input root."""
    record = device.inputs["images"][name]
    path = root / record["path"]
    if not path.is_file():
        raise GenerateError(f"Missing input {path}")
    if path.stat().st_size != record["size"] or sha256(path) != record["sha256"]:
        raise GenerateError(f"Input {path} does not match {device.name}-inputs.json")
    return path


def parse_props(text: str) -> dict[str, str]:
    props = {}
    for line in text.splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            props[key] = value
    return props


def require_prop(props: dict[str, str], key: str, source: str) -> str:
    if key not in props:
        raise GenerateError(f"{source} has no {key}")
    return props[key]


def lz4_block(src: bytes, out: bytearray) -> None:
    """Decompress one LZ4 block, appending to out."""
    i = 0
    while True:
        token = src[i]
        i += 1
        length = token >> 4
        if length == 15:
            while src[i] == 255:
                length += 255
                i += 1
            length += src[i]
            i += 1
        out += src[i : i + length]
        i += length
        if i >= len(src):
            return
        offset = src[i] | src[i + 1] << 8
        i += 2
        length = token & 15
        if length == 15:
            while src[i] == 255:
                length += 255
                i += 1
            length += src[i]
            i += 1
        length += 4
        start = len(out) - offset
        if offset == 0 or start < 0:
            raise GenerateError("Corrupt LZ4 block")
        # A match may overlap the bytes it produces, repeating its last offset bytes.
        pattern = out[start : start + min(offset, length)]
        repeats, rest = divmod(length, len(pattern))
        out += pattern * repeats + pattern[:rest]


def lz4_legacy(data: bytes) -> bytes:
    """Decompress the legacy LZ4 format that boot image ramdisks use."""
    if data[:4] != LZ4_LEGACY_MAGIC:
        raise GenerateError("Expected a legacy LZ4 ramdisk")
    out = bytearray()
    i = 4
    while i < len(data):
        (size,) = struct.unpack_from("<I", data, i)
        i += 4
        # Concatenated streams repeat the magic.
        if data[i - 4 : i] != LZ4_LEGACY_MAGIC:
            lz4_block(data[i : i + size], out)
            i += size
    return bytes(out)


def cpio_files(data: bytes) -> dict[str, bytes]:
    """Return the regular files of a newc archive."""
    files = {}
    offset = 0
    while True:
        if data[offset : offset + 6] != b"070701":
            raise GenerateError("Invalid CPIO header in the recovery ramdisk")
        fields = [
            int(data[offset + 6 + i * 8 : offset + 14 + i * 8], 16) for i in range(13)
        ]
        mode, size, name_size = fields[1], fields[6], fields[11]
        offset += 110
        name = data[offset : offset + name_size - 1].decode()
        offset = (offset + name_size + 3) & ~3
        if name == "TRAILER!!!":
            return files
        if stat.S_ISREG(mode):
            files[name] = data[offset : offset + size]
        offset = (offset + size + 3) & ~3


def read_recovery(path: Path) -> Recovery:
    """Unpack the ramdisk of a kernel-less boot image header v3 or v4."""
    data = path.read_bytes()
    if data[:8] != BOOT_MAGIC:
        raise GenerateError(f"{path} is not a boot image")
    kernel_size, ramdisk_size = struct.unpack_from("<II", data, 8)
    (version,) = struct.unpack_from("<I", data, 40)
    if version not in (3, 4) or kernel_size != 0:
        raise GenerateError(f"{path}: expected header v3 or v4 without a kernel")
    # From v3 on, the page size is fixed at 4096 and the ramdisk follows the header page.
    ramdisk = data[4096 : 4096 + ramdisk_size]
    files = cpio_files(lz4_legacy(ramdisk))
    props = parse_props(files["prop.default"].decode())
    return Recovery(len(data), version, files, props)


def elf_needed(data: bytes, path: str) -> list[str]:
    """Return the DT_NEEDED entries of a 64-bit AArch64 ELF file."""
    if (
        data[:4] != b"\x7fELF"
        or data[4:6] != b"\x02\x01"
        or struct.unpack_from("<H", data, 18)[0] != EM_AARCH64
    ):
        raise GenerateError(f"{path} is not a 64-bit AArch64 ELF file")
    (shoff,) = struct.unpack_from("<Q", data, 0x28)
    shentsize, shnum = struct.unpack_from("<HH", data, 0x3A)
    # sh_type, sh_offset, sh_size and sh_link of each section header.
    sections = [
        struct.unpack_from("<4xI16xQQI", data, shoff + i * shentsize)
        for i in range(shnum)
    ]
    dynamic = [section for section in sections if section[0] == 6]  # SHT_DYNAMIC
    if len(dynamic) != 1:
        raise GenerateError(f"{path} has no dynamic section")
    _, offset, size, link = dynamic[0]
    _, strtab, _, _ = sections[link]
    needed = []
    for entry in range(offset, offset + size, 16):
        tag, value = struct.unpack_from("<QQ", data, entry)
        if tag == 0:  # DT_NULL
            break
        if tag == 1:  # DT_NEEDED
            end = data.index(b"\0", strtab + value)
            needed.append(data[strtab + value : end].decode())
    return needed


def axml_strings(data: bytes, offset: int) -> list[str]:
    """Read a ResStringPool chunk."""
    header_size = struct.unpack_from("<H", data, offset + 2)[0]
    count, _, flags, start, _ = struct.unpack_from("<5I", data, offset + 8)
    positions = struct.unpack_from(f"<{count}I", data, offset + header_size)
    strings = []
    for position in positions:
        i = offset + start + position
        if flags & 0x100:  # UTF-8: UTF-16 length, then UTF-8 length
            i += 2 if data[i] & 0x80 else 1
            length = data[i]
            if length & 0x80:
                length = (length & 0x7F) << 8 | data[i + 1]
                i += 1
            strings.append(data[i + 1 : i + 1 + length].decode())
        else:
            (length,) = struct.unpack_from("<H", data, i)
            if length & 0x8000:
                length = (length & 0x7FFF) << 16 | struct.unpack_from(
                    "<H", data, i + 2
                )[0]
                i += 2
            strings.append(data[i + 2 : i + 2 + 2 * length].decode("utf-16-le"))
    return strings


def axml_value(strings: list[str], raw: int, kind: int, data: int) -> str:
    if raw != 0xFFFFFFFF:
        return strings[raw]
    if kind == 0x03:  # string
        return strings[data]
    if kind == 0x10:  # decimal
        return str(struct.unpack("<i", struct.pack("<I", data))[0])
    if kind == 0x11:  # hexadecimal
        return f"0x{data:08x}"
    if kind == 0x12:  # boolean
        return "true" if data else "false"
    if kind == 0x04:  # float
        return repr(struct.unpack("<f", struct.pack("<I", data))[0])
    return f"@0x{data:08x}"  # reference and other types, unused by the decoded files


@dataclass
class XmlNode:
    tag: str
    attrs: list[tuple[str, str]]
    children: list[XmlNode] = field(default_factory=list)
    text: str | None = None

    def lines(self, depth: int = 0) -> list[str]:
        pad = "    " * depth
        attrs = "".join(f' {name}="{xml_escape(value)}"' for name, value in self.attrs)
        if self.text is not None:
            return [f"{pad}<{self.tag}{attrs}>{xml_escape(self.text)}</{self.tag}>"]
        if not self.children:
            return [f"{pad}<{self.tag}{attrs}/>"]
        inner = [line for child in self.children for line in child.lines(depth + 1)]
        return [f"{pad}<{self.tag}{attrs}>", *inner, f"{pad}</{self.tag}>"]


def xml_escape(text: str) -> str:
    for char, entity in (("&", "&amp;"), ("<", "&lt;"), (">", "&gt;"), ('"', "&quot;")):
        text = text.replace(char, entity)
    return text


def axml(data: bytes, name: str) -> XmlNode:
    """Decode a compiled (binary) Android XML file, keeping raw attribute values."""
    if struct.unpack_from("<H", data)[0] != 0x0003:
        raise GenerateError(f"{name} is not a compiled XML file")
    strings: list[str] = []
    stack = [XmlNode("", [])]
    offset = 8
    while offset < len(data):
        kind, _, size = struct.unpack_from("<HHI", data, offset)
        if kind == 0x0001:  # string pool
            strings = axml_strings(data, offset)
        elif kind == 0x0102:  # start element
            _, tag, start, stride, count = struct.unpack_from(
                "<IIHHH", data, offset + 16
            )
            attrs = []
            for i in range(count):
                _, attr, raw, _, _, value_kind, value = struct.unpack_from(
                    "<IIIHBBI", data, offset + 16 + start + i * stride
                )
                attrs.append(
                    (strings[attr], axml_value(strings, raw, value_kind, value))
                )
            node = XmlNode(strings[tag], attrs)
            stack[-1].children.append(node)
            stack.append(node)
        elif kind == 0x0103:  # end element
            stack.pop()
        elif kind == 0x0104:  # character data
            stack[-1].text = strings[struct.unpack_from("<I", data, offset + 16)[0]]
        offset += size
    if len(stack) != 1 or len(stack[0].children) != 1:
        raise GenerateError(f"{name} is not a well-formed compiled XML file")
    return stack[0].children[0]


def apk_package(data: bytes, name: str) -> str:
    with zipfile.ZipFile(io.BytesIO(data)) as apk:
        manifest = axml(apk.read("AndroidManifest.xml"), name)
    return dict(manifest.attrs)["package"]


def check_recipes(device: Device) -> None:
    """Keep the dependency one-way: recipes never reference the generated tree."""
    for path in sorted((TREE / device.mk_path).rglob("*")):
        if not path.is_file():
            continue
        if path.name == "BoardConfig.mk":
            raise GenerateError(
                f"Only the generated tree may have a BoardConfig.mk: {path}"
            )
        if device.out_path in path.read_text(errors="replace"):
            raise GenerateError(f"Recipe references the generated tree: {path}")


def board_makefile(device: Device, props: dict[str, str], recovery: Recovery) -> str:
    config = device.config
    out = device.out_path
    density = int(require_prop(props, "ro.sf.lcd_density", "Stock vendor/build.prop"))
    corner = round(config["recovery"]["rounded_corner_radius_dp"] * density / 160)
    lines = [
        f"# {HEADER}",
        f"include {device.mk_path}/device/{device.name}/BoardConfig-base.mk",
        "",
        f"TARGET_BOOTLOADER_BOARD_NAME := {config['bootloader_board_name']}",
        f"TARGET_SCREEN_DENSITY := {density}",
        "",
    ]
    for name in config["prebuilt_images"]:
        lines.append(
            f"BOARD_PREBUILT_{name.upper()}IMAGE := {out}/{STOCK_DIR}/{name}.img"
        )
    for name in config["prebuilt_images"]:
        if name not in ("boot", "vendor"):
            lines.append(f"TARGET_COPY_OUT_{name.upper()} := {name}")
    lines.append("")
    for name, fs_type in config["built_partitions"].items():
        lines.append(f"BOARD_{name.upper()}IMAGE_FILE_SYSTEM_TYPE := {fs_type}")
    lines.append("")
    super_config = config["super"]
    groups = super_config["groups"]
    lines.append(f"BOARD_SUPER_PARTITION_SIZE := {super_config['size']}")
    lines.append(f"BOARD_SUPER_PARTITION_GROUPS := {' '.join(groups)}")
    for group, value in groups.items():
        lines.append(f"BOARD_{group.upper()}_SIZE := {value['size']}")
        lines.append(
            f"BOARD_{group.upper()}_PARTITION_LIST := {' '.join(value['partitions'])}"
        )
    lines.append("")
    lines.append(f"AB_OTA_PARTITIONS := {' '.join(config['ab_ota_partitions'])}")
    lines.append("")
    init_boot = config["init_boot"]
    version = init_boot["header_version"]
    lines += [
        f"BOARD_INIT_BOOT_IMAGE_PARTITION_SIZE := {init_boot['partition_size']}",
        f"BOARD_INIT_BOOT_IMAGE_PAGESIZE := {init_boot['page_size']}",
        f"BOARD_BOOT_HEADER_VERSION := {version}",
        f"BOARD_INIT_BOOT_HEADER_VERSION := {version}",
        f"BOARD_RAMDISK_USE_LZ4 := {'true' if init_boot['lz4_ramdisk'] else 'false'}",
        "# The stock header carries no OS version or patch level.",
        f"BOARD_MKBOOTIMG_INIT_ARGS += --header_version {version} --os_version 0 --os_patch_level 0",
        "",
        "# Like the stock recovery: a ramdisk only, booted with the kernel of boot.",
        f"BOARD_RECOVERYIMAGE_PARTITION_SIZE := {recovery.partition_size}",
        "BOARD_EXCLUDE_KERNEL_FROM_RECOVERY_IMAGE := true",
        f"BOARD_RECOVERY_MKBOOTIMG_ARGS := --header_version {recovery.header_version}",
        f"TARGET_RECOVERY_FSTAB := {out}/{RECOVERY_DIR}/{config['recovery']['fstab']}",
        f"TARGET_RECOVERY_PIXEL_FORMAT := {require_prop(recovery.props, 'ro.minui.pixel_format', 'Stock recovery prop.default')}",
        f"TARGET_RECOVERY_UI_SCREEN_WIDTH := {config['recovery']['screen_width']}",
        "# Keep the menu out of the rounded display corners.",
        f"TARGET_RECOVERY_UI_MARGIN_HEIGHT := {corner}",
        f"TARGET_RECOVERY_UI_MARGIN_WIDTH := {corner}",
    ]
    return "\n".join(lines) + "\n"


def product_makefile(
    device: Device, props: dict[str, str], sections: dict[str, Section]
) -> str:
    config = device.config

    def prop(key: str) -> str:
        return require_prop(props, key, "Stock vendor/build.prop")

    identity = {
        "NAME": config["product"],
        "DEVICE": device.name,
        "BRAND": prop("ro.product.vendor.brand"),
        "MODEL": prop("ro.product.vendor.model"),
        "MANUFACTURER": prop("ro.product.vendor.manufacturer"),
    }
    lines = [
        f"# {HEADER}",
        f"include {device.out_path}/{VERSION_CHECK}",
        "",
        f"$(call inherit-product, {device.mk_path}/device/{device.name}/device.mk)",
        "",
    ]
    lines += [f"PRODUCT_{key} := {value}" for key, value in identity.items()]
    lines += [f"PRODUCT_SYSTEM_{key} := {value}" for key, value in identity.items()]
    lines += [
        "",
        f"PRODUCT_SHIPPING_API_LEVEL := {prop('ro.product.first_api_level')}",
        "",
        f"PRODUCT_PACKAGES += {matrix_module(device)}",
    ]
    for comment, section in sections.items():
        lines += ["", f"# {comment}"]
        if section.modules:
            lines += make_list("PRODUCT_PACKAGES", section.modules)
        if section.copies:
            lines += make_list("PRODUCT_COPY_FILES", section.copies)
    return "\n".join(lines) + "\n"


def make_list(variable: str, items: list[str]) -> list[str]:
    """Append items to a make variable, one per line."""
    return [
        f"{variable} += \\",
        *(f"    {item} \\" for item in items[:-1]),
        f"    {items[-1]}",
    ]


def matrix_module(device: Device) -> str:
    return f"{device.name.lower()}_framework_compatibility_matrix"


def matrix_blueprint(device: Device) -> str:
    return f"""// {HEADER}

package {{
    default_applicable_licenses: ["Android-Apache-2.0"],
}}

// Installed on system_ext: generic_system.mk doesn't allow device files on system.
vintf_compatibility_matrix {{
    name: "{matrix_module(device)}",
    stem: "compatibility_matrix.{device.name.lower()}.xml",
    system_ext_specific: true,
    srcs: ["compatibility_matrix.device.xml"],
}}
"""


def blueprint(kind: str, props: list[str]) -> str:
    body = "\n".join(f"    {line}" for line in props)
    return f"{kind} {{\n{body}\n}}\n"


def elf_props(path: str, data: bytes) -> list[str]:
    """Declare the libraries a stock ELF file links, so that the build installs them.

    A missing library then fails the build instead of the device at run time.
    """
    libs = [lib for lib in elf_needed(data, path) if lib not in IMPLICIT_LIBS]
    shared_libs = ", ".join(f'"{lib.removesuffix(".so")}"' for lib in libs)
    return [
        f"shared_libs: [{shared_libs}],",
        "strip: { none: true },",
        "// 4 KiB aligned, and built against the stock versions of these libraries.",
        "check_elf_files: false,",
    ]


def library_props(name: str, src: str) -> list[str]:
    return [
        f'name: "{name}",',
        'compile_multilib: "64",',
        f'target: {{ android_arm64: {{ srcs: ["{src}"] }} }},',
    ]


def recovery_section(device: Device, recovery: Recovery) -> Section:
    """Take the device HALs, their scripts and the fstab from the stock recovery."""
    config = device.config["recovery"]
    wanted = [config["fstab"], *config["modules"], *config["files"]]
    missing = [path for path in wanted if path not in recovery.files]
    if missing:
        raise GenerateError(f"Stock recovery ramdisk lacks {', '.join(missing)}")
    section = Section()
    for path in wanted:
        section.files[f"{RECOVERY_DIR}/{path}"] = recovery.files[path]
    for path in config["files"]:
        if recovery.files[path][:4] == b"\x7fELF":
            raise GenerateError(f"{path} is an ELF file; list it under modules")
        section.copies.append(
            f"{device.out_path}/{RECOVERY_DIR}/{path}:$(TARGET_COPY_OUT_RECOVERY)/root/{path}"
        )
    src_dir = posixpath.relpath(RECOVERY_DIR, PROPRIETARY)
    for path in config["modules"]:
        directory, base = posixpath.split(path)
        src = f"{src_dir}/{path}"
        if directory == "system/bin" or directory.startswith("system/bin/"):
            name = base
            kind = "cc_prebuilt_binary"
            props = [f'name: "{name}",', f'srcs: ["{src}"],']
            if directory != "system/bin":
                hw = posixpath.relpath(directory, "system/bin")
                props.append(f'relative_install_path: "{hw}",')
        elif directory == "system/lib64" and base.endswith(".so"):
            name = base.removesuffix(".so")
            kind = "cc_prebuilt_library_shared"
            props = library_props(name, src)
        else:
            raise GenerateError(f"No prebuilt module type for {path}")
        props += [
            f'owner: "{device.vendor}",',
            "recovery: true,",
            *elf_props(path, recovery.files[path]),
        ]
        section.modules.append(name)
        section.blueprints.append(blueprint(kind, props))
    return section


def stock_file(device: Device, root: Path, path: str) -> Path:
    """Resolve <tree>/<path> to a regular file in an unpacked stock partition."""
    tree, rest = path.split("/", 1)
    if tree not in device.inputs["trees"]:
        raise GenerateError(f"No input tree {tree} for {path}")
    file = root / device.inputs["trees"][tree] / rest
    if file.is_symlink() or not file.is_file():
        raise GenerateError(f"Missing stock file {file}")
    return file


def privapp_allowlist(
    device: Device, root: Path, src: str, package: str
) -> tuple[str, str]:
    """Keep only the package's block of the stock privileged permission allowlists.

    The framework reads an app's allowlist from the partition the app is on.
    """
    tree = src.split("/", 1)[0]
    directory = root / device.inputs["trees"][tree] / "etc/permissions"
    blocks = [
        (xml.name, node)
        for xml in sorted(directory.glob("*.xml"))
        for node in ET.parse(xml).getroot().iter("privapp-permissions")
        if node.get("package") == package
    ]
    if len(blocks) != 1:
        raise GenerateError(f"Expected one allowlist for {package} in {directory}")
    source, node = blocks[0]
    allowlist = ET.Element("permissions")
    allowlist.append(node)
    ET.indent(allowlist, space="    ")
    name = f"privapp-permissions-{package}.xml"
    return name, (
        f'<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {HEADER} From the stock {tree}/etc/permissions/{source}. -->\n"
        f"{ET.tostring(allowlist, encoding='unicode')}\n"
    )


def proprietary_section(device: Device, root: Path) -> Section:
    """Install the configured stock files of the built partitions.

    Each entry is a path in an unpacked stock tree, installed at the same path, or a
    {"from", "to"} pair. The install path picks the module type.
    """
    section = Section()
    entries = [
        (entry, entry) if isinstance(entry, str) else (entry["from"], entry["to"])
        for entry in device.config["proprietary"]
    ]
    installed = {f"/{dst}" for _, dst in entries}
    for src, dst in entries:
        file = stock_file(device, root, src)
        data = file.read_bytes()
        partition, rel = dst.split("/", 1)
        if partition not in PARTITIONS:
            raise GenerateError(f"Can't install stock files to {partition}: {dst}")
        flag, copy_out = PARTITIONS[partition]
        section.files[f"{PROPRIETARY}/{dst}"] = data
        directory, base = posixpath.split(rel)
        owner = f'owner: "{device.vendor}",'
        if directory.split("/")[0] in ("app", "priv-app") and base.endswith(".apk"):
            name = base.removesuffix(".apk")
            if posixpath.basename(directory) != name:
                raise GenerateError(f"Expected {directory}/{name}.apk: {dst}")
            privileged = directory.startswith("priv-app/")
            props = [
                f'name: "{name}",',
                owner,
                f'apk: "{dst}",',
                'certificate: "platform",',
            ]
            if privileged:
                props.append("privileged: true,")
            props += [
                "// Compiled for the stock Android version, so not against this boot image.",
                "dex_preopt: { enabled: false },",
                flag,
            ]
            section.modules.append(name)
            section.blueprints.append(blueprint("android_app_import", props))
            # Stock links the app's JNI libraries to the shared copies.
            for link in sorted(p for p in file.parent.rglob("*") if p.is_symlink()):
                target = link.readlink().as_posix()
                if target not in installed:
                    raise GenerateError(
                        f"{link} points to {target}, which isn't installed"
                    )
                location = f"{directory}/{link.relative_to(file.parent).as_posix()}"
                module = f"{name}_symlink_{link.name.removesuffix('.so')}"
                section.modules.append(module)
                section.blueprints.append(
                    blueprint(
                        "install_symlink",
                        [
                            f'name: "{module}",',
                            f'installed_location: "{location}",',
                            f'symlink_target: "{target}",',
                            flag,
                        ],
                    )
                )
            if privileged:
                package = apk_package(data, dst)
                allowlist, text = privapp_allowlist(device, root, src, package)
                section.texts[f"permissions/{allowlist}"] = text
                section.copies.append(
                    f"{device.out_path}/permissions/{allowlist}:{copy_out}/etc/permissions/{allowlist}"
                )
        elif directory == "framework" and base.endswith(".jar"):
            name = base.removesuffix(".jar")
            props = [f'name: "{name}",', owner, f'jars: ["{dst}"],', flag]
            section.modules.append(name)
            section.blueprints.append(blueprint("dex_import", props))
        elif directory == "lib64" and base.endswith(".so"):
            name = base.removesuffix(".so")
            props = [*library_props(name, dst), owner, flag, *elf_props(dst, data)]
            section.modules.append(name)
            section.blueprints.append(blueprint("cc_prebuilt_library_shared", props))
        elif directory == "etc" or directory.startswith("etc/"):
            section.copies.append(
                f"{device.out_path}/{PROPRIETARY}/{dst}:{copy_out}/{rel}"
            )
        else:
            raise GenerateError(f"No way to install {dst}")
    return section


def keep_country(carriers: XmlNode, mcc: str, name: str) -> None:
    """Keep the carrier_config blocks of one mobile country code.

    CarrierConfig applies vendor.xml after its own per-carrier configs, and a block
    without filters matches every SIM. Limiting that block to the country keeps the
    platform's configs for other SIMs and changes nothing for the country's own.
    """
    if carriers.tag != "carrier_config_list":
        raise GenerateError(f"{name} is not a carrier config list")
    kept = []
    for block in carriers.children:
        filters = dict(block.attrs)
        if not filters:
            block.attrs = [("mcc", mcc)]
        elif "mcc" not in filters:
            raise GenerateError(
                f"Review the carrier_config filters {filters} in {name}"
            )
        elif filters["mcc"] != mcc:
            continue
        kept.append(block)
    carriers.children = kept


def resource_value(name: str, value: object) -> list[str] | None:
    """Resource XML for a bool, integer, string or list of numbers from the configuration."""
    if isinstance(value, bool):
        return [f'    <bool name="{name}">{str(value).lower()}</bool>']
    if isinstance(value, int):
        return [f'    <integer name="{name}">{value}</integer>']
    if isinstance(value, str):
        return [
            f'    <string name="{name}" translatable="false">{xml_escape(value)}</string>'
        ]
    if (
        isinstance(value, list)
        and value
        and all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in value)
    ):
        # Items keep their JSON spelling, so 80 compiles to an integer and 5.1 to a float.
        tag = "integer-array" if all(isinstance(v, int) for v in value) else "array"
        return [
            f'    <{tag} name="{name}">',
            *(f"        <item>{v}</item>" for v in value),
            f"    </{tag}>",
        ]
    return None


def overlay_section(device: Device, root: Path) -> Section:
    """Rebuild stock resource values as static runtime resource overlays.

    Values come either from the configuration, with their stock source noted there, or
    from the compiled XML resources of a stock overlay.
    """
    section = Section()
    for module, spec in device.config["overlays"].items():
        target = spec["target"]
        base = f"overlays/{module}"
        props = [
            f'name: "{module}",',
            'certificate: "platform",',
            'sdk_version: "current",',
            "product_specific: true,",
        ]
        if "values" in spec:
            values = []
            for name, value in spec["values"].items():
                lines = resource_value(name, value)
                if lines is None:
                    raise GenerateError(f"Unsupported overlay value {module}/{name}")
                values += lines
            section.texts[f"{base}/res/values/config.xml"] = "\n".join(
                [
                    '<?xml version="1.0" encoding="utf-8"?>',
                    f"<!-- {HEADER} -->",
                    "<resources>",
                    *values,
                    "</resources>",
                    "",
                ]
            )
        if "xml" in spec:
            src = spec["xml"]
            with zipfile.ZipFile(stock_file(device, root, src)) as apk:
                names = sorted(n for n in apk.namelist() if n.startswith("res/xml/"))
                if not names:
                    raise GenerateError(f"{src} has no XML resources")
                for name in names:
                    node = axml(apk.read(name), f"{src}:{name}")
                    origin = f"From the stock {src}:{name}"
                    if "mcc" in spec:
                        keep_country(node, spec["mcc"], f"{src}:{name}")
                        origin += f", keeping mcc {spec['mcc']} only"
                    section.texts[f"{base}/{name}"] = "\n".join(
                        [
                            "<?xml version='1.0' encoding='utf-8' standalone='yes' ?>",
                            f"<!-- {HEADER} {origin}. -->",
                            *node.lines(),
                            "",
                        ]
                    )
            props += [
                '// Carrier matching compares raw strings: an mnc of "03" must stay "03".',
                'aaptflags: ["--keep-raw-values"],',
            ]
        section.texts[f"{base}/AndroidManifest.xml"] = "\n".join(
            [
                '<?xml version="1.0" encoding="utf-8"?>',
                f"<!-- {HEADER} -->",
                '<manifest xmlns:android="http://schemas.android.com/apk/res/android"',
                f'    package="{target}.overlay.common">',
                '    <application android:hasCode="false" />',
                f'    <overlay android:targetPackage="{target}" android:isStatic="true" />',
                "</manifest>",
                "",
            ]
        )
        section.texts[f"{base}/Android.bp"] = f"// {HEADER}\n\n" + blueprint(
            "runtime_resource_overlay", props
        )
        section.modules.append(module)
    return section


def compatibility_matrix(device: Device, root: Path) -> str:
    """Declare the stock vendor HAL interfaces so that the framework accepts them.

    Only vendor.* AIDL HALs with explicit instances are listed. This adds no
    implementations and makes no claim that the framework can use them.
    """
    paths: list[Path] = []
    for tree, patterns in device.config["vintf_manifests"].items():
        base = root / device.inputs["trees"][tree]
        for pattern in patterns:
            matches = sorted(base.glob(pattern))
            if not matches and "*" not in pattern:
                raise GenerateError(f"Missing VINTF manifest {base / pattern}")
            paths += matches
    inventory: defaultdict[tuple[str, str], set[tuple[str, str]]] = defaultdict(set)
    for path in paths:
        for hal in ET.parse(path).getroot().findall("hal"):
            name = hal.findtext("name") or ""
            if not name.startswith("vendor."):
                continue
            if hal.get("format") != "aidl":
                raise GenerateError(f"Review the non-AIDL vendor HAL {name} in {path}")
            versions = [node.text or "" for node in hal.findall("version")] or ["1"]
            instances: list[tuple[str, str]] = []
            for node in hal.findall("fqname"):
                interface, instance = (node.text or "").split("/", 1)
                instances.append((interface, instance))
            for interface in hal.findall("interface"):
                instances += [
                    (interface.findtext("name") or "", node.text or "")
                    for node in interface.findall("instance")
                ]
            if not instances:
                raise GenerateError(f"{name} in {path} lists no instances")
            for version in versions:
                inventory[(name, version)].update(instances)
    matrix = ET.Element("compatibility-matrix", version="2.0", type="framework")
    for (name, version), declared in sorted(inventory.items()):
        hal = ET.SubElement(matrix, "hal", format="aidl")
        ET.SubElement(hal, "name").text = name
        ET.SubElement(hal, "version").text = version
        groups: defaultdict[str, list[str]] = defaultdict(list)
        for interface, instance in sorted(declared):
            groups[interface].append(instance)
        for interface, names in groups.items():
            node = ET.SubElement(hal, "interface")
            ET.SubElement(node, "name").text = interface
            for instance in names:
                ET.SubElement(node, "instance").text = instance
    ET.indent(matrix, space="    ")
    return f"<!-- {HEADER} -->\n{ET.tostring(matrix, encoding='unicode')}\n"


def version_check(device: Device) -> str:
    """Make the build notice when mdevtool has moved on since the last generation.

    Development builds warn; builds with MDEVTOOL_RELEASE=true fail.
    """
    result = subprocess.run(
        ["git", "-C", str(MDEVTOOL), "rev-parse", "HEAD"],
        check=False,
        capture_output=True,
        text=True,
    )
    if result.returncode == 0:
        revision = result.stdout.strip()
        problem = f"""MDEVTOOL_VERSION_PROBLEM :=
ifneq ($(strip $(shell git -C {MDEVTOOL_PATH} rev-parse HEAD 2>/dev/null)),{revision})
  MDEVTOOL_VERSION_PROBLEM := {device.out_path} is out of date: run {MDEVTOOL_PATH}/generate.py
endif"""
    else:
        problem = (
            "MDEVTOOL_VERSION_PROBLEM := "
            f"{device.out_path} was generated from uncommitted {MDEVTOOL_PATH}"
        )
    return f"""# {HEADER}
{problem}
ifneq ($(MDEVTOOL_VERSION_PROBLEM),)
  ifeq ($(MDEVTOOL_RELEASE),true)
    $(error $(MDEVTOOL_VERSION_PROBLEM))
  else
    $(warning $(MDEVTOOL_VERSION_PROBLEM))
  endif
endif
"""


def products_list(device: Device) -> str:
    return (
        f"# {HEADER}\nPRODUCT_MAKEFILES += $(LOCAL_DIR)/{device.config['product']}.mk\n"
    )


def write_output(
    out: Path, files: dict[str, bytes], links: dict[str, Path]
) -> tuple[int, int]:
    """Make out hold exactly these files and links, and leave the rest alone.

    A file rewritten with the same content still gets a new mtime, and the build then
    redoes everything that depends on it: the permission XMLs alone make it recompile
    the framework. So only what differs is written, and what is no longer generated is
    removed. Returns the number of paths written and removed.
    """
    if out.is_symlink() or (out.exists() and not out.is_dir()):
        raise GenerateError(f"{out} is not a directory")
    if out.exists() and not (out / MARKER).is_file():
        raise GenerateError(f"Refusing to write to {out}: it has no {MARKER} marker")
    wanted = files.keys() | links.keys()
    removed = 0
    for top, dirs, names in os.walk(out, topdown=False):
        directory = Path(top)
        # os.walk lists links to directories with the directories, without entering.
        for name in [*names, *(d for d in dirs if (directory / d).is_symlink())]:
            if (directory / name).relative_to(out).as_posix() not in wanted:
                (directory / name).unlink()
                removed += 1
        if directory != out and not any(directory.iterdir()):
            directory.rmdir()
    written = 0
    for relative, content in files.items():
        target = out / relative
        if target.is_symlink():
            target.unlink()
        elif target.is_file() and target.read_bytes() == content:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
        written += 1
    for relative, link in links.items():
        target = out / relative
        if target.is_symlink() and target.readlink() == link:
            continue
        target.unlink(missing_ok=True)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.symlink_to(link)
        written += 1
    return written, removed


def snapshot(out: Path, root: Path) -> dict[str, dict[str, str]]:
    """Describe the generated tree: file hashes, and links relative to the input root."""
    entries = {}
    for path in sorted(out.rglob("*")):
        relative = path.relative_to(out).as_posix()
        if relative in VOLATILE:
            continue
        if path.is_symlink():
            entries[relative] = {"input": path.readlink().relative_to(root).as_posix()}
        elif path.is_file():
            entries[relative] = {"sha256": sha256(path)}
    return entries


def update_skels(device: Device, texts: dict[str, str]) -> None:
    """Keep a copy of the generated text files; stock files are not copied."""
    skels = MDEVTOOL / "vendor-skels"
    skels.mkdir(exist_ok=True)
    # Keep the copies out of Soong and product discovery.
    (skels / ".find-ignore").touch()
    if device.skel_dir.exists():
        shutil.rmtree(device.skel_dir)
    for relative, text in texts.items():
        target = device.skel_dir / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)


def compare_spec(device: Device, entries: dict[str, dict[str, str]]) -> None:
    if not device.spec_file.is_file():
        raise GenerateError(
            f"No {device.spec_file}; review the output and rerun with --update-spec"
        )
    expected = json.loads(device.spec_file.read_text())
    if expected == entries:
        return
    old = json.dumps(expected, indent=2).splitlines()
    new = json.dumps(entries, indent=2).splitlines()
    diff = "\n".join(difflib.unified_diff(old, new, "spec", "generated", lineterm=""))
    raise GenerateError(
        f"Output differs from {device.spec_file}:\n{diff}\n"
        "Review the change, then rerun with --update-spec."
    )


def generate(device: Device, root: Path, update_spec: bool) -> None:
    check_recipes(device)
    images = {
        name: verify_input(device, root, name)
        for name in device.config["prebuilt_images"]
    }
    recovery = read_recovery(verify_input(device, root, "recovery"))
    props = parse_props(
        (root / device.inputs["trees"]["vendor"] / "build.prop").read_text()
    )
    sections = {
        "From the stock recovery ramdisk.": recovery_section(device, recovery),
        "From the stock system_ext and product.": proprietary_section(device, root),
        "Stock resource values.": overlay_section(device, root),
    }
    texts = {
        "AndroidProducts.mk": products_list(device),
        f"{device.config['product']}.mk": product_makefile(device, props, sections),
        "BoardConfig.mk": board_makefile(device, props, recovery),
        "Android.bp": matrix_blueprint(device),
        "compatibility_matrix.device.xml": compatibility_matrix(device, root),
        f"{PROPRIETARY}/Android.bp": f"// {HEADER}\n\n"
        + "\n".join(block for s in sections.values() for block in s.blueprints),
    }
    files: dict[str, bytes] = {}
    for section in sections.values():
        texts.update(section.texts)
        files.update(section.files)
    files.update((relative, text.encode()) for relative, text in texts.items())
    files[MARKER] = f"{HEADER}\n".encode()
    files[VERSION_CHECK] = version_check(device).encode()
    links = {f"{STOCK_DIR}/{name}.img": path for name, path in images.items()}
    out = TREE / device.out_path
    written, removed = write_output(out, files, links)
    entries = snapshot(out, root)
    if update_spec:
        device.spec_file.parent.mkdir(parents=True, exist_ok=True)
        device.spec_file.write_text(json.dumps(entries, indent=2) + "\n")
        update_skels(device, texts)
    else:
        compare_spec(device, entries)
    print(
        f"Generated {device.out_path} ({len(entries)} entries; "
        f"{written} written, {removed} removed)"
    )


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate the vendor tree of a device."
    )
    parser.add_argument("device", help="device name, such as NX809J")
    parser.add_argument(
        "--input-root",
        type=Path,
        required=True,
        help="directory holding the stock inputs",
    )
    parser.add_argument(
        "--update-spec",
        action="store_true",
        help="accept the output as the new vendor-specs and vendor-skels",
    )
    args = parser.parse_args()
    try:
        generate(load_device(args.device), args.input_root.resolve(), args.update_spec)
    except GenerateError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
