#!/usr/bin/env python3
"""Generate the vendor tree of a device from its stock firmware.

The output, vendor/<vendor>/<device> in the source tree, is not kept in git. Each
run deletes it and writes it again from:

* config/device/<device>.json: stock facts and what to build from them;
* config/device/<device>-inputs.json: the stock inputs and their hashes;
* config/mk/<vendor>/: hand-written recipes, included by the generated makefiles.

Stock files are copied from the ramdisk of the stock recovery image, which the
generator unpacks itself, so the inputs are only images and unpacked partition trees.

The result is compared with vendor-specs/<vendor>/<device>.json. When the output
changes on purpose, rerun with --update-spec and commit the new spec together with
vendor-skels/<vendor>/<device>, a copy of the generated text files.
"""

from __future__ import annotations

import argparse
import difflib
import hashlib
import json
import posixpath
import shutil
import stat
import struct
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

MDEVTOOL = Path(__file__).resolve().parent
TREE = MDEVTOOL.parents[1]
MDEVTOOL_PATH = "vendor/mdevtool"
MARKER = ".mdevtool-generated"
VERSION_CHECK = "mdevtool-version-check.mk"
# Files that legitimately differ between runs; kept out of specs and skels.
VOLATILE = {MARKER, VERSION_CHECK}
HEADER = "Generated by vendor/mdevtool/generate.py. Do not edit."
# Stock files: images linked from the input root and files copied out of them,
# with the Soong modules for the copied ELF files in PROPRIETARY/Android.bp.
PROPRIETARY = "proprietary"
STOCK_DIR = f"{PROPRIETARY}/stock"
RECOVERY_DIR = f"{PROPRIETARY}/recovery"
BOOT_MAGIC = b"ANDROID!"
LZ4_LEGACY_MAGIC = b"\x02\x21\x4c\x18"
EM_AARCH64 = 183
# Linked by every module without being declared.
IMPLICIT_LIBS = {"libc.so", "libm.so", "libdl.so", "libc++.so"}


class GenerateError(Exception):
    pass


@dataclass
class Recovery:
    """What the generated tree takes from the stock recovery image."""

    partition_size: int
    header_version: int
    files: dict[str, bytes]
    props: dict[str, str]


@dataclass
class Device:
    config: dict
    inputs: dict

    @property
    def vendor(self) -> str:
        return self.config["vendor"]

    @property
    def name(self) -> str:
        return self.config["device"]

    @property
    def out_path(self) -> str:
        return f"vendor/{self.vendor}/{self.name}"

    @property
    def mk_path(self) -> str:
        return f"{MDEVTOOL_PATH}/config/mk/{self.vendor}"

    @property
    def spec_file(self) -> Path:
        return MDEVTOOL / "vendor-specs" / self.vendor / f"{self.name}.json"

    @property
    def skel_dir(self) -> Path:
        return MDEVTOOL / "vendor-skels" / self.vendor / self.name


def load_device(name: str) -> Device:
    directory = MDEVTOOL / "config/device"
    try:
        config = json.loads((directory / f"{name}.json").read_text())
        inputs = json.loads((directory / f"{name}-inputs.json").read_text())
    except FileNotFoundError as error:
        raise GenerateError(
            f"Unknown device {name}: {error.filename} is missing"
        ) from None
    return Device(config, inputs)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as file:
        while chunk := file.read(1 << 20):
            digest.update(chunk)
    return digest.hexdigest()


def verify_input(device: Device, root: Path, name: str) -> Path:
    """Check a stock image and return its path under the input root."""
    record = device.inputs["images"][name]
    path = root / record["path"]
    if not path.is_file():
        raise GenerateError(f"Missing input {path}")
    if path.stat().st_size != record["size"] or sha256(path) != record["sha256"]:
        raise GenerateError(f"Input {path} does not match {device.name}-inputs.json")
    return path


def parse_props(text: str) -> dict[str, str]:
    props = {}
    for line in text.splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            props[key] = value
    return props


def require_prop(props: dict[str, str], key: str, source: str) -> str:
    if key not in props:
        raise GenerateError(f"{source} has no {key}")
    return props[key]


def lz4_block(src: bytes, out: bytearray) -> None:
    """Decompress one LZ4 block, appending to out."""
    i = 0
    while True:
        token = src[i]
        i += 1
        length = token >> 4
        if length == 15:
            while src[i] == 255:
                length += 255
                i += 1
            length += src[i]
            i += 1
        out += src[i : i + length]
        i += length
        if i >= len(src):
            return
        offset = src[i] | src[i + 1] << 8
        i += 2
        length = token & 15
        if length == 15:
            while src[i] == 255:
                length += 255
                i += 1
            length += src[i]
            i += 1
        length += 4
        start = len(out) - offset
        if offset == 0 or start < 0:
            raise GenerateError("Corrupt LZ4 block")
        # A match may overlap the bytes it produces, repeating its last offset bytes.
        pattern = out[start : start + min(offset, length)]
        repeats, rest = divmod(length, len(pattern))
        out += pattern * repeats + pattern[:rest]


def lz4_legacy(data: bytes) -> bytes:
    """Decompress the legacy LZ4 format that boot image ramdisks use."""
    if data[:4] != LZ4_LEGACY_MAGIC:
        raise GenerateError("Expected a legacy LZ4 ramdisk")
    out = bytearray()
    i = 4
    while i < len(data):
        (size,) = struct.unpack_from("<I", data, i)
        i += 4
        # Concatenated streams repeat the magic.
        if data[i - 4 : i] != LZ4_LEGACY_MAGIC:
            lz4_block(data[i : i + size], out)
            i += size
    return bytes(out)


def cpio_files(data: bytes) -> dict[str, bytes]:
    """Return the regular files of a newc archive."""
    files = {}
    offset = 0
    while True:
        if data[offset : offset + 6] != b"070701":
            raise GenerateError("Invalid CPIO header in the recovery ramdisk")
        fields = [
            int(data[offset + 6 + i * 8 : offset + 14 + i * 8], 16) for i in range(13)
        ]
        mode, size, name_size = fields[1], fields[6], fields[11]
        offset += 110
        name = data[offset : offset + name_size - 1].decode()
        offset = (offset + name_size + 3) & ~3
        if name == "TRAILER!!!":
            return files
        if stat.S_ISREG(mode):
            files[name] = data[offset : offset + size]
        offset = (offset + size + 3) & ~3


def read_recovery(path: Path) -> Recovery:
    """Unpack the ramdisk of a kernel-less boot image header v3 or v4."""
    data = path.read_bytes()
    if data[:8] != BOOT_MAGIC:
        raise GenerateError(f"{path} is not a boot image")
    kernel_size, ramdisk_size = struct.unpack_from("<II", data, 8)
    (version,) = struct.unpack_from("<I", data, 40)
    if version not in (3, 4) or kernel_size != 0:
        raise GenerateError(f"{path}: expected header v3 or v4 without a kernel")
    # From v3 on, the page size is fixed at 4096 and the ramdisk follows the header page.
    ramdisk = data[4096 : 4096 + ramdisk_size]
    files = cpio_files(lz4_legacy(ramdisk))
    props = parse_props(files["prop.default"].decode())
    return Recovery(len(data), version, files, props)


def elf_needed(data: bytes, path: str) -> list[str]:
    """Return the DT_NEEDED entries of a 64-bit AArch64 ELF file."""
    if (
        data[:4] != b"\x7fELF"
        or data[4:6] != b"\x02\x01"
        or struct.unpack_from("<H", data, 18)[0] != EM_AARCH64
    ):
        raise GenerateError(f"{path} is not a 64-bit AArch64 ELF file")
    (shoff,) = struct.unpack_from("<Q", data, 0x28)
    shentsize, shnum = struct.unpack_from("<HH", data, 0x3A)
    # sh_type, sh_offset, sh_size and sh_link of each section header.
    sections = [
        struct.unpack_from("<4xI16xQQI", data, shoff + i * shentsize)
        for i in range(shnum)
    ]
    dynamic = [section for section in sections if section[0] == 6]  # SHT_DYNAMIC
    if len(dynamic) != 1:
        raise GenerateError(f"{path} has no dynamic section")
    _, offset, size, link = dynamic[0]
    _, strtab, _, _ = sections[link]
    needed = []
    for entry in range(offset, offset + size, 16):
        tag, value = struct.unpack_from("<QQ", data, entry)
        if tag == 0:  # DT_NULL
            break
        if tag == 1:  # DT_NEEDED
            end = data.index(b"\0", strtab + value)
            needed.append(data[strtab + value : end].decode())
    return needed


def check_recipes(device: Device) -> None:
    """Keep the dependency one-way: recipes never reference the generated tree."""
    for path in sorted((TREE / device.mk_path).rglob("*")):
        if not path.is_file():
            continue
        if path.name == "BoardConfig.mk":
            raise GenerateError(
                f"Only the generated tree may have a BoardConfig.mk: {path}"
            )
        if device.out_path in path.read_text(errors="replace"):
            raise GenerateError(f"Recipe references the generated tree: {path}")


def board_makefile(device: Device, props: dict[str, str], recovery: Recovery) -> str:
    config = device.config
    out = device.out_path
    density = int(require_prop(props, "ro.sf.lcd_density", "Stock vendor/build.prop"))
    corner = round(config["recovery"]["rounded_corner_radius_dp"] * density / 160)
    lines = [
        f"# {HEADER}",
        f"include {device.mk_path}/device/{device.name}/BoardConfig-base.mk",
        "",
        f"TARGET_BOOTLOADER_BOARD_NAME := {config['bootloader_board_name']}",
        f"TARGET_SCREEN_DENSITY := {density}",
        "",
    ]
    for name in config["prebuilt_images"]:
        lines.append(
            f"BOARD_PREBUILT_{name.upper()}IMAGE := {out}/{STOCK_DIR}/{name}.img"
        )
    for name in config["prebuilt_images"]:
        if name not in ("boot", "vendor"):
            lines.append(f"TARGET_COPY_OUT_{name.upper()} := {name}")
    lines.append("")
    for name, fs_type in config["built_partitions"].items():
        lines.append(f"BOARD_{name.upper()}IMAGE_FILE_SYSTEM_TYPE := {fs_type}")
    lines.append("")
    super_config = config["super"]
    groups = super_config["groups"]
    lines.append(f"BOARD_SUPER_PARTITION_SIZE := {super_config['size']}")
    lines.append(f"BOARD_SUPER_PARTITION_GROUPS := {' '.join(groups)}")
    for group, value in groups.items():
        lines.append(f"BOARD_{group.upper()}_SIZE := {value['size']}")
        lines.append(
            f"BOARD_{group.upper()}_PARTITION_LIST := {' '.join(value['partitions'])}"
        )
    lines.append("")
    lines.append(f"AB_OTA_PARTITIONS := {' '.join(config['ab_ota_partitions'])}")
    lines.append("")
    init_boot = config["init_boot"]
    version = init_boot["header_version"]
    lines += [
        f"BOARD_INIT_BOOT_IMAGE_PARTITION_SIZE := {init_boot['partition_size']}",
        f"BOARD_INIT_BOOT_IMAGE_PAGESIZE := {init_boot['page_size']}",
        f"BOARD_BOOT_HEADER_VERSION := {version}",
        f"BOARD_INIT_BOOT_HEADER_VERSION := {version}",
        f"BOARD_RAMDISK_USE_LZ4 := {'true' if init_boot['lz4_ramdisk'] else 'false'}",
        "# The stock header carries no OS version or patch level.",
        f"BOARD_MKBOOTIMG_INIT_ARGS += --header_version {version} --os_version 0 --os_patch_level 0",
        "",
        "# Like the stock recovery: a ramdisk only, booted with the kernel of boot.",
        f"BOARD_RECOVERYIMAGE_PARTITION_SIZE := {recovery.partition_size}",
        "BOARD_EXCLUDE_KERNEL_FROM_RECOVERY_IMAGE := true",
        f"BOARD_RECOVERY_MKBOOTIMG_ARGS := --header_version {recovery.header_version}",
        f"TARGET_RECOVERY_FSTAB := {out}/{RECOVERY_DIR}/{config['recovery']['fstab']}",
        f"TARGET_RECOVERY_PIXEL_FORMAT := {require_prop(recovery.props, 'ro.minui.pixel_format', 'Stock recovery prop.default')}",
        f"TARGET_RECOVERY_UI_SCREEN_WIDTH := {config['recovery']['screen_width']}",
        "# Keep the menu out of the rounded display corners.",
        f"TARGET_RECOVERY_UI_MARGIN_HEIGHT := {corner}",
        f"TARGET_RECOVERY_UI_MARGIN_WIDTH := {corner}",
    ]
    return "\n".join(lines) + "\n"


def product_makefile(device: Device, props: dict[str, str], modules: list[str]) -> str:
    config = device.config

    def prop(key: str) -> str:
        return require_prop(props, key, "Stock vendor/build.prop")

    identity = {
        "NAME": config["product"],
        "DEVICE": device.name,
        "BRAND": prop("ro.product.vendor.brand"),
        "MODEL": prop("ro.product.vendor.model"),
        "MANUFACTURER": prop("ro.product.vendor.manufacturer"),
    }
    lines = [
        f"# {HEADER}",
        f"include {device.out_path}/{VERSION_CHECK}",
        "",
        f"$(call inherit-product, {device.mk_path}/device/{device.name}/device.mk)",
        "",
    ]
    lines += [f"PRODUCT_{key} := {value}" for key, value in identity.items()]
    lines += [f"PRODUCT_SYSTEM_{key} := {value}" for key, value in identity.items()]
    lines += [
        "",
        f"PRODUCT_SHIPPING_API_LEVEL := {prop('ro.product.first_api_level')}",
        "",
        f"PRODUCT_PACKAGES += {matrix_module(device)}",
        "",
        "# From the stock recovery ramdisk.",
        *make_list("PRODUCT_PACKAGES", modules),
        *make_list(
            "PRODUCT_COPY_FILES",
            [
                f"{device.out_path}/{RECOVERY_DIR}/{path}:$(TARGET_COPY_OUT_RECOVERY)/root/{path}"
                for path in config["recovery"]["files"]
            ],
        ),
    ]
    return "\n".join(lines) + "\n"


def make_list(variable: str, items: list[str]) -> list[str]:
    """Append items to a make variable, one per line."""
    return [
        f"{variable} += \\",
        *(f"    {item} \\" for item in items[:-1]),
        f"    {items[-1]}",
    ]


def matrix_module(device: Device) -> str:
    return f"{device.name.lower()}_framework_compatibility_matrix"


def matrix_blueprint(device: Device) -> str:
    return f"""// {HEADER}

package {{
    default_applicable_licenses: ["Android-Apache-2.0"],
}}

// Installed on system_ext: generic_system.mk doesn't allow device files on system.
vintf_compatibility_matrix {{
    name: "{matrix_module(device)}",
    stem: "compatibility_matrix.{device.name.lower()}.xml",
    system_ext_specific: true,
    srcs: ["compatibility_matrix.device.xml"],
}}
"""


def recovery_module(device: Device, path: str, data: bytes) -> tuple[str, str]:
    """Describe a stock ELF file of the recovery ramdisk as a prebuilt module.

    ELF files can't go through PRODUCT_COPY_FILES. Declaring the libraries that a
    file links makes the build install them in the recovery ramdisk as well.
    """
    libs = [lib for lib in elf_needed(data, path) if lib not in IMPLICIT_LIBS]
    shared_libs = ", ".join(f'"{lib.removesuffix(".so")}"' for lib in libs)
    directory, base = posixpath.split(path)
    src = f'"{posixpath.relpath(RECOVERY_DIR, PROPRIETARY)}/{path}"'
    if directory == "system/bin" or directory.startswith("system/bin/"):
        name = base
        kind = "cc_prebuilt_binary"
        props = [f"srcs: [{src}],"]
        if directory != "system/bin":
            props.append(
                f'relative_install_path: "{posixpath.relpath(directory, "system/bin")}",'
            )
    elif directory == "system/lib64" and base.endswith(".so"):
        name = base.removesuffix(".so")
        kind = "cc_prebuilt_library_shared"
        props = [
            'compile_multilib: "64",',
            f"target: {{ android_arm64: {{ srcs: [{src}] }} }},",
        ]
    else:
        raise GenerateError(f"No prebuilt module type for {path}")
    body = "\n".join(
        f"    {line}"
        for line in [
            f'name: "{name}",',
            f'owner: "{device.vendor}",',
            *props,
            f"shared_libs: [{shared_libs}],",
            "recovery: true,",
            "strip: { none: true },",
            "// 4 KiB aligned, and built against the stock versions of these libraries.",
            "check_elf_files: false,",
        ]
    )
    return name, f"{kind} {{\n{body}\n}}\n"


def recovery_blueprint(blocks: list[str]) -> str:
    return f"// {HEADER}\n\n" + "\n".join(blocks)


def compatibility_matrix(device: Device, root: Path) -> str:
    """Declare the stock vendor HAL interfaces so that the framework accepts them.

    Only vendor.* AIDL HALs with explicit instances are listed. This adds no
    implementations and makes no claim that the framework can use them.
    """
    paths: list[Path] = []
    for tree, patterns in device.config["vintf_manifests"].items():
        base = root / device.inputs["trees"][tree]
        for pattern in patterns:
            matches = sorted(base.glob(pattern))
            if not matches and "*" not in pattern:
                raise GenerateError(f"Missing VINTF manifest {base / pattern}")
            paths += matches
    inventory: defaultdict[tuple[str, str], set[tuple[str, str]]] = defaultdict(set)
    for path in paths:
        for hal in ET.parse(path).getroot().findall("hal"):
            name = hal.findtext("name") or ""
            if not name.startswith("vendor."):
                continue
            if hal.get("format") != "aidl":
                raise GenerateError(f"Review the non-AIDL vendor HAL {name} in {path}")
            versions = [node.text or "" for node in hal.findall("version")] or ["1"]
            instances: list[tuple[str, str]] = []
            for node in hal.findall("fqname"):
                interface, instance = (node.text or "").split("/", 1)
                instances.append((interface, instance))
            for interface in hal.findall("interface"):
                instances += [
                    (interface.findtext("name") or "", node.text or "")
                    for node in interface.findall("instance")
                ]
            if not instances:
                raise GenerateError(f"{name} in {path} lists no instances")
            for version in versions:
                inventory[(name, version)].update(instances)
    matrix = ET.Element("compatibility-matrix", version="2.0", type="framework")
    for (name, version), declared in sorted(inventory.items()):
        hal = ET.SubElement(matrix, "hal", format="aidl")
        ET.SubElement(hal, "name").text = name
        ET.SubElement(hal, "version").text = version
        groups: defaultdict[str, list[str]] = defaultdict(list)
        for interface, instance in sorted(declared):
            groups[interface].append(instance)
        for interface, names in groups.items():
            node = ET.SubElement(hal, "interface")
            ET.SubElement(node, "name").text = interface
            for instance in names:
                ET.SubElement(node, "instance").text = instance
    ET.indent(matrix, space="    ")
    return f"<!-- {HEADER} -->\n{ET.tostring(matrix, encoding='unicode')}\n"


def version_check(device: Device) -> str:
    """Make the build notice when mdevtool has moved on since the last generation.

    Development builds warn; builds with MDEVTOOL_RELEASE=true fail.
    """
    result = subprocess.run(
        ["git", "-C", str(MDEVTOOL), "rev-parse", "HEAD"],
        check=False,
        capture_output=True,
        text=True,
    )
    if result.returncode == 0:
        revision = result.stdout.strip()
        problem = f"""MDEVTOOL_VERSION_PROBLEM :=
ifneq ($(strip $(shell git -C {MDEVTOOL_PATH} rev-parse HEAD 2>/dev/null)),{revision})
  MDEVTOOL_VERSION_PROBLEM := {device.out_path} is out of date: run {MDEVTOOL_PATH}/generate.py
endif"""
    else:
        problem = (
            "MDEVTOOL_VERSION_PROBLEM := "
            f"{device.out_path} was generated from uncommitted {MDEVTOOL_PATH}"
        )
    return f"""# {HEADER}
{problem}
ifneq ($(MDEVTOOL_VERSION_PROBLEM),)
  ifeq ($(MDEVTOOL_RELEASE),true)
    $(error $(MDEVTOOL_VERSION_PROBLEM))
  else
    $(warning $(MDEVTOOL_VERSION_PROBLEM))
  endif
endif
"""


def products_list(device: Device) -> str:
    return (
        f"# {HEADER}\nPRODUCT_MAKEFILES += $(LOCAL_DIR)/{device.config['product']}.mk\n"
    )


def reset_output(out: Path) -> None:
    if out.is_symlink() or (out.exists() and not out.is_dir()):
        raise GenerateError(f"{out} is not a directory")
    if out.exists():
        if not (out / MARKER).is_file():
            raise GenerateError(f"Refusing to delete {out}: it has no {MARKER} marker")
        shutil.rmtree(out)
    out.mkdir(parents=True)


def snapshot(out: Path, root: Path) -> dict[str, dict[str, str]]:
    """Describe the generated tree: file hashes, and links relative to the input root."""
    entries = {}
    for path in sorted(out.rglob("*")):
        relative = path.relative_to(out).as_posix()
        if relative in VOLATILE:
            continue
        if path.is_symlink():
            entries[relative] = {"input": path.readlink().relative_to(root).as_posix()}
        elif path.is_file():
            entries[relative] = {"sha256": sha256(path)}
    return entries


def update_skels(device: Device, texts: dict[str, str]) -> None:
    """Keep a copy of the generated text files; stock files are not copied."""
    skels = MDEVTOOL / "vendor-skels"
    skels.mkdir(exist_ok=True)
    # Keep the copies out of Soong and product discovery.
    (skels / ".find-ignore").touch()
    if device.skel_dir.exists():
        shutil.rmtree(device.skel_dir)
    for relative, text in texts.items():
        target = device.skel_dir / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)


def compare_spec(device: Device, entries: dict[str, dict[str, str]]) -> None:
    if not device.spec_file.is_file():
        raise GenerateError(
            f"No {device.spec_file}; review the output and rerun with --update-spec"
        )
    expected = json.loads(device.spec_file.read_text())
    if expected == entries:
        return
    old = json.dumps(expected, indent=2).splitlines()
    new = json.dumps(entries, indent=2).splitlines()
    diff = "\n".join(difflib.unified_diff(old, new, "spec", "generated", lineterm=""))
    raise GenerateError(
        f"Output differs from {device.spec_file}:\n{diff}\n"
        "Review the change, then rerun with --update-spec."
    )


def recovery_files(device: Device, recovery: Recovery) -> dict[str, bytes]:
    config = device.config["recovery"]
    wanted = [config["fstab"], *config["modules"], *config["files"]]
    missing = [path for path in wanted if path not in recovery.files]
    if missing:
        raise GenerateError(f"Stock recovery ramdisk lacks {', '.join(missing)}")
    for path in config["files"]:
        if recovery.files[path][:4] == b"\x7fELF":
            raise GenerateError(f"{path} is an ELF file; list it under modules")
    return {f"{RECOVERY_DIR}/{path}": recovery.files[path] for path in wanted}


def generate(device: Device, root: Path, update_spec: bool) -> None:
    check_recipes(device)
    images = {
        name: verify_input(device, root, name)
        for name in device.config["prebuilt_images"]
    }
    recovery = read_recovery(verify_input(device, root, "recovery"))
    props = parse_props(
        (root / device.inputs["trees"]["vendor"] / "build.prop").read_text()
    )
    stock_files = recovery_files(device, recovery)
    modules = [
        recovery_module(device, path, recovery.files[path])
        for path in device.config["recovery"]["modules"]
    ]
    texts = {
        "AndroidProducts.mk": products_list(device),
        f"{device.config['product']}.mk": product_makefile(
            device, props, [name for name, _ in modules]
        ),
        "BoardConfig.mk": board_makefile(device, props, recovery),
        "Android.bp": matrix_blueprint(device),
        "compatibility_matrix.device.xml": compatibility_matrix(device, root),
        f"{PROPRIETARY}/Android.bp": recovery_blueprint(
            [block for _, block in modules]
        ),
    }
    out = TREE / device.out_path
    reset_output(out)
    (out / MARKER).write_text(f"{HEADER}\n")
    (out / VERSION_CHECK).write_text(version_check(device))
    for relative, text in texts.items():
        (out / relative).parent.mkdir(parents=True, exist_ok=True)
        (out / relative).write_text(text)
    for relative, data in stock_files.items():
        (out / relative).parent.mkdir(parents=True, exist_ok=True)
        (out / relative).write_bytes(data)
    stock = out / STOCK_DIR
    stock.mkdir(parents=True)
    for name, path in images.items():
        (stock / f"{name}.img").symlink_to(path)
    entries = snapshot(out, root)
    if update_spec:
        device.spec_file.parent.mkdir(parents=True, exist_ok=True)
        device.spec_file.write_text(json.dumps(entries, indent=2) + "\n")
        update_skels(device, texts)
    else:
        compare_spec(device, entries)
    print(f"Generated {device.out_path} ({len(entries)} entries)")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate the vendor tree of a device."
    )
    parser.add_argument("device", help="device name, such as NX809J")
    parser.add_argument(
        "--input-root",
        type=Path,
        required=True,
        help="directory holding the stock inputs",
    )
    parser.add_argument(
        "--update-spec",
        action="store_true",
        help="accept the output as the new vendor-specs and vendor-skels",
    )
    args = parser.parse_args()
    try:
        generate(load_device(args.device), args.input_root.resolve(), args.update_spec)
    except GenerateError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
